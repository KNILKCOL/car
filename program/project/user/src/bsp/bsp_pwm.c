/*********************************************************************************************************************
* 文件名称          bsp_pwm.c
* 功能简介          PWM BSP 驱动 —— 无源蜂鸣器 + PWM 波形输出（任务5）
********************************************************************************************************************/
#include "bsp_pwm.h"

static uint8  bsp_buzzer_on_flag = 0;                                           // 蜂鸣器发声状态
static uint32 bsp_buzzer_freq    = BSP_BUZZER_FREQ_HZ;                          // 当前频率
static uint16 bsp_buzzer_left_ms = 0;                                           // 非阻塞发声剩余时间

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     蜂鸣器初始化
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void bsp_buzzer_init (void)
{
    // 初始化 PWM：初始占空比 0 => 上电静音
    pwm_init(BSP_BUZZER_PWM_CHANNEL, BSP_BUZZER_FREQ_HZ, BSP_BUZZER_DUTY_OFF);

    bsp_buzzer_on_flag = 0;
    bsp_buzzer_freq    = BSP_BUZZER_FREQ_HZ;
    bsp_buzzer_left_ms = 0;
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     蜂鸣器开始发声
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void bsp_buzzer_on (void)
{
    pwm_set_duty(BSP_BUZZER_PWM_CHANNEL, BSP_BUZZER_DUTY_ON);
    bsp_buzzer_on_flag = 1;
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     蜂鸣器停止发声
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void bsp_buzzer_off (void)
{
    pwm_set_duty(BSP_BUZZER_PWM_CHANNEL, BSP_BUZZER_DUTY_OFF);
    bsp_buzzer_on_flag = 0;
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     设置蜂鸣器发声频率
// 参数说明     freq_hz      频率(Hz)
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void bsp_buzzer_set_freq (uint32 freq_hz)
{
    if(0 == freq_hz)
    {
        return;
    }

    bsp_buzzer_freq = freq_hz;
    pwm_set_freq(BSP_BUZZER_PWM_CHANNEL, freq_hz,
                 bsp_buzzer_on_flag ? BSP_BUZZER_DUTY_ON : BSP_BUZZER_DUTY_OFF);
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     设置蜂鸣器占空比
// 参数说明     duty         占空比 0 ~ PWM_DUTY_MAX
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void bsp_buzzer_set_duty (uint32 duty)
{
    if(duty > PWM_DUTY_MAX)
    {
        duty = PWM_DUTY_MAX;
    }

    pwm_set_duty(BSP_BUZZER_PWM_CHANNEL, duty);
    bsp_buzzer_on_flag = (0 != duty) ? (1) : (0);
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     蜂鸣器响一声（阻塞方式）
// 参数说明     ms           持续时间(ms)
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void bsp_buzzer_beep (uint32 ms)
{
    bsp_buzzer_on();
    system_delay_ms(ms);
    bsp_buzzer_off();
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     蜂鸣器响一声（非阻塞方式）
// 参数说明     ms           持续时间(ms)
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void bsp_buzzer_beep_start (uint32 ms)
{
    if(ms > 0xFFFF)
    {
        ms = 0xFFFF;
    }

    bsp_buzzer_left_ms = (uint16)ms;
    bsp_buzzer_on();
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     蜂鸣器非阻塞计时（1ms 系统节拍调用）
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void bsp_buzzer_tick_1ms (void)
{
    if(bsp_buzzer_left_ms > 0)
    {
        bsp_buzzer_left_ms--;
        if(0 == bsp_buzzer_left_ms)
        {
            bsp_buzzer_off();
        }
    }
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     查询蜂鸣器是否正在发声
// 返回参数     uint8        1-正在发声 0-静音
//-------------------------------------------------------------------------------------------------------------------
uint8 bsp_buzzer_is_on (void)
{
    return bsp_buzzer_on_flag;
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     查询蜂鸣器当前频率
// 返回参数     uint32       Hz
//-------------------------------------------------------------------------------------------------------------------
uint32 bsp_buzzer_get_freq (void)
{
    return bsp_buzzer_freq;
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     第二路 PWM 演示输出初始化
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void bsp_pwm_demo_init (void)
{
#if BSP_PWM_DEMO_ENABLE
    pwm_init(BSP_PWM_DEMO_CHANNEL, BSP_PWM_DEMO_FREQ_HZ, BSP_PWM_DEMO_DUTY);
#endif
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     设置第二路 PWM 的频率与占空比
// 参数说明     freq_hz      频率(Hz)
// 参数说明     duty         占空比 0 ~ PWM_DUTY_MAX
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void bsp_pwm_demo_set (uint32 freq_hz, uint32 duty)
{
#if BSP_PWM_DEMO_ENABLE
    if(0 == freq_hz)
    {
        return;
    }
    if(duty > PWM_DUTY_MAX)
    {
        duty = PWM_DUTY_MAX;
    }
    pwm_set_freq(BSP_PWM_DEMO_CHANNEL, freq_hz, duty);
#endif
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     设置第二路 PWM 的占空比
// 参数说明     duty         占空比 0 ~ PWM_DUTY_MAX
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void bsp_pwm_demo_set_duty (uint32 duty)
{
#if BSP_PWM_DEMO_ENABLE
    if(duty > PWM_DUTY_MAX)
    {
        duty = PWM_DUTY_MAX;
    }
    pwm_set_duty(BSP_PWM_DEMO_CHANNEL, duty);
#endif
}
