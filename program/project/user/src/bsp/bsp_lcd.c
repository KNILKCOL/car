/*********************************************************************************************************************
* 文件名称          bsp_lcd.c
* 功能简介          SPI 屏幕 BSP 驱动（任务7）
********************************************************************************************************************/
#include "bsp_lcd.h"

static uint8 bsp_lcd_backlight = 1;                                             // 背光状态

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     屏幕初始化
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void bsp_lcd_init (void)
{
    tft180_init();                                                              // 内部完成 SPI2(PB13/PB15) 与 DC/RES/CS/BL 的初始化
    tft180_set_dir(BSP_LCD_DIR);                                                // 设置显示方向
    tft180_set_font(BSP_LCD_FONT);                                              // 设置字体
    tft180_set_color(RGB565_BLACK, RGB565_WHITE);                               // 默认黑字白底
    tft180_clear();
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     整屏填充
// 参数说明     color        RGB565 颜色
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void bsp_lcd_clear (uint16 color)
{
    tft180_full(color);
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     在指定行列显示字符串（黑色字 / 白色底）
// 参数说明     col, row     行列
// 参数说明     str          字符串（超出本行剩余宽度的部分会被自动截断）
// 返回参数     void
// 备注信息     开源库的 tft180_show_string 会按 x + 8*j 逐个画字符且不做范围检查，
//               字符串一旦超过屏幕宽度就会触发 zf_device_tft180.c 里的坐标断言，
//               因此本层必须先把字符串截断到本行还能放下的字符数。
//-------------------------------------------------------------------------------------------------------------------
void bsp_lcd_puts (uint16 col, uint16 row, const char *str)
{
    bsp_lcd_puts_color(col, row, str, RGB565_BLACK, RGB565_WHITE);
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     在指定行列显示字符串（自定义颜色）
// 参数说明     col, row     行列
// 参数说明     str          字符串（超出本行剩余宽度的部分会被自动截断）
// 参数说明     pen, bg      前景色 / 背景色
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void bsp_lcd_puts_color (uint16 col, uint16 row, const char *str, uint16 pen, uint16 bg)
{
    char   line[BSP_LCD_COLS + 1];
    uint16 max_chars;
    uint16 len;

    if((col >= BSP_LCD_COLS) || (row >= BSP_LCD_ROWS) || (0 == str))
    {
        return;
    }

    max_chars = (uint16)(BSP_LCD_COLS - col);                                   // 本行还能放下的字符数

    len = (uint16)strlen(str);
    if(len > max_chars)
    {
        len = max_chars;
    }

    memcpy(line, str, len);
    line[len] = '\0';

    tft180_set_color(pen, bg);
    tft180_show_string((uint16)(col * BSP_LCD_CH_W), (uint16)(row * BSP_LCD_CH_H), line);
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     在指定行列显示整数
// 参数说明     col, row     行列
// 参数说明     dat          数值
// 参数说明     num          显示位数（超过本行剩余宽度时会自动收窄）
// 参数说明     pen, bg      前景色 / 背景色
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void bsp_lcd_put_int (uint16 col, uint16 row, int32 dat, uint8 num, uint16 pen, uint16 bg)
{
    if((col >= BSP_LCD_COLS) || (row >= BSP_LCD_ROWS) || (0 == num))
    {
        return;
    }

    // 开源库断言要求 1 <= num <= 10，同时不能超出本行剩余宽度
    if(num > 10)
    {
        num = 10;
    }
    if(num > (BSP_LCD_COLS - col))
    {
        num = (uint8)(BSP_LCD_COLS - col);
    }

    tft180_set_color(pen, bg);
    tft180_show_int((uint16)(col * BSP_LCD_CH_W), (uint16)(row * BSP_LCD_CH_H), dat, num);
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     清空一整行
// 参数说明     row          行号
// 参数说明     bg           背景色
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void bsp_lcd_clear_row (uint16 row, uint16 bg)
{
    if(row >= BSP_LCD_ROWS)
    {
        return;
    }

    bsp_lcd_fill_rect(0, (uint16)(row * BSP_LCD_CH_H), BSP_LCD_W, BSP_LCD_CH_H, bg);
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     填充一个矩形区域
// 参数说明     x, y         左上角坐标(像素)
// 参数说明     w, h         宽 / 高(像素)
// 参数说明     color        RGB565 颜色
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void bsp_lcd_fill_rect (uint16 x, uint16 y, uint16 w, uint16 h, uint16 color)
{
    uint16 i;

    for(i = 0; i < h; i++)
    {
        tft180_draw_line(x, (uint16)(y + i), (uint16)(x + w - 1), (uint16)(y + i), color);
    }
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     显示测试图案（任务7：验证 SPI 屏幕驱动是否正常工作）
// 备注信息     依次显示红/绿/蓝/白 纯色 + 三色边框，肉眼即可判断屏幕工作正常
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void bsp_lcd_draw_test_pattern (void)
{
    bsp_lcd_clear(RGB565_RED);
    system_delay_ms(250);
    bsp_lcd_clear(RGB565_GREEN);
    system_delay_ms(250);
    bsp_lcd_clear(RGB565_BLUE);
    system_delay_ms(250);
    bsp_lcd_clear(RGB565_WHITE);
    system_delay_ms(250);

    bsp_lcd_clear(RGB565_BLACK);
    tft180_set_color(RGB565_BLACK, RGB565_WHITE);
    tft180_draw_line(0, 0, BSP_LCD_W - 1, 0, RGB565_RED);
    tft180_draw_line(0, 0, 0, BSP_LCD_H - 1, RGB565_GREEN);
    tft180_draw_line(0, BSP_LCD_H - 1, BSP_LCD_W - 1, BSP_LCD_H - 1, RGB565_BLUE);
    tft180_draw_line(BSP_LCD_W - 1, 0, BSP_LCD_W - 1, BSP_LCD_H - 1, RGB565_YELLOW);
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     屏幕背光开关
// 参数说明     on           1-打开背光 0-关闭背光
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void bsp_lcd_set_backlight (uint8 on)
{
    bsp_lcd_backlight = (0 != on) ? (1) : (0);
    TFT180_BLK(bsp_lcd_backlight ? (1) : (0));
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     查询背光状态
// 返回参数     uint8        1-开 0-关
//-------------------------------------------------------------------------------------------------------------------
uint8 bsp_lcd_get_backlight (void)
{
    return bsp_lcd_backlight;
}
