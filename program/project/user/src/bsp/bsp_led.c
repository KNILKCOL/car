/*********************************************************************************************************************
* 文件名称          bsp_led.c
* 功能简介          LED 指示灯 BSP 驱动（任务3 / 任务6）
* 硬件连接          LIGHT1_A11 / LIGHT2_A12 / LIGHT3_A15 / LIGHT4_D1
********************************************************************************************************************/
#include "bsp_led.h"

// LED 引脚表（顺序对应 bsp_led_on(1) ~ bsp_led_on(BSP_LED_NUM)）
static const gpio_pin_enum bsp_led_pin_table[BSP_LED_NUM] =
{
    BSP_LED1_PIN,   // A11
    BSP_LED2_PIN,   // A12
    BSP_LED3_PIN,   // A15
    BSP_LED4_PIN,   // D1
};

static uint8 bsp_led_state[BSP_LED_NUM] = {0};

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     LED 初始化
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void bsp_led_init (void)
{
    uint8 i;

    for(i = 0; i < BSP_LED_NUM; i++)
    {
        // 初始化引脚：推挽输出，默认输出"熄灭电平"
        gpio_init(bsp_led_pin_table[i], GPO, BSP_LED_OFF_LEVEL, GPO_PUSH_PULL);
        bsp_led_state[i] = 0;
    }
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     获取指定编号 LED 对应的引脚
// 参数说明     index        LED 编号 1 ~ BSP_LED_NUM
// 返回参数     gpio_pin_enum
//-------------------------------------------------------------------------------------------------------------------
gpio_pin_enum bsp_led_pin (uint8 index)
{
    if((index < 1) || (index > BSP_LED_NUM))
    {
        return PIN_NULL;
    }
    return bsp_led_pin_table[index - 1];
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     设置指定编号 LED 的状态
// 参数说明     index        LED 编号 1 ~ BSP_LED_NUM
// 参数说明     state        0-熄灭 1-点亮
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void bsp_led_set (uint8 index, uint8 state)
{
    gpio_pin_enum pin = bsp_led_pin(index);

    if(PIN_NULL == pin)
    {
        return;
    }

    if(0 == state)
    {
        gpio_set_level(pin, BSP_LED_OFF_LEVEL);
        bsp_led_state[index - 1] = 0;
    }
    else
    {
        gpio_set_level(pin, BSP_LED_ON_LEVEL);
        bsp_led_state[index - 1] = 1;
    }
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     点亮指定编号的 LED
// 参数说明     index        LED 编号 1 ~ BSP_LED_NUM
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void bsp_led_on (uint8 index)
{
    bsp_led_set(index, 1);
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     熄灭指定编号的 LED
// 参数说明     index        LED 编号 1 ~ BSP_LED_NUM
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void bsp_led_off (uint8 index)
{
    bsp_led_set(index, 0);
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     翻转指定编号的 LED
// 参数说明     index        LED 编号 1 ~ BSP_LED_NUM
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void bsp_led_toggle (uint8 index)
{
    gpio_pin_enum pin = bsp_led_pin(index);

    if(PIN_NULL == pin)
    {
        return;
    }

    // 直接操作寄存器翻转（可在定时器中断中安全调用）
    if(bsp_led_state[index - 1] == 0)
    {
        gpio_set_level(pin, BSP_LED_ON_LEVEL);
        bsp_led_state[index - 1] = 1;
    }
    else
    {
        gpio_set_level(pin, BSP_LED_OFF_LEVEL);
        bsp_led_state[index - 1] = 0;
    }
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     读取指定编号 LED 当前状态
// 参数说明     index        LED 编号 1 ~ BSP_LED_NUM
// 返回参数     uint8        0-熄灭 1-点亮
//-------------------------------------------------------------------------------------------------------------------
uint8 bsp_led_get (uint8 index)
{
    if((index < 1) || (index > BSP_LED_NUM))
    {
        return 0;
    }
    return bsp_led_state[index - 1];
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     所有 LED 全开
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void bsp_led_all_on (void)
{
    uint8 i;
    for(i = 1; i <= BSP_LED_NUM; i++)
    {
        bsp_led_on(i);
    }
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     所有 LED 全关
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void bsp_led_all_off (void)
{
    uint8 i;
    for(i = 1; i <= BSP_LED_NUM; i++)
    {
        bsp_led_off(i);
    }
}
