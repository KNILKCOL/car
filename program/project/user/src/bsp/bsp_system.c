/*********************************************************************************************************************
* 文件名称          bsp_system.c
* 功能简介          板级统一初始化入口（BSP 层）
********************************************************************************************************************/
#include "bsp_system.h"
#include "bsp_led.h"
#include "bsp_key.h"
#include "bsp_pwm.h"
#include "bsp_pit.h"
#include "bsp_lcd.h"

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     BSP 统一初始化
// 备注信息     顺序很重要：
//               1. 先配置系统时钟（后续所有外设分频都依赖它）
//               2. debug_init 是开源库要求必须保留的初始化（MPU + 时钟 + 调试串口）
//               3. 再初始化各外设
//               4. 最后打开定时器中断，保证中断里用到的外设已经就绪
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void bsp_system_init (void)
{
    //-------------------------------------------------- 1. 系统时钟 --------------------------------------------------
    clock_init(BSP_SYSTEM_CLOCK);

    //-------------------------------------------------- 2. 调试串口 --------------------------------------------------
#if BSP_DEBUG_ENABLE
    debug_init();
#endif

    //-------------------------------------------------- 3. 各外设 ----------------------------------------------------
    bsp_led_init();                                                             // 任务3：LED
    bsp_key_init();                                                             // 任务4/9：按键 + 外部中断
    bsp_buzzer_init();                                                          // 任务5：无源蜂鸣器 PWM
    bsp_pwm_demo_init();                                                        // 任务5：第二路 PWM 波形输出
    bsp_lcd_init();                                                             // 任务7：SPI 屏幕

    //-------------------------------------------------- 4. 定时器中断 ------------------------------------------------
    bsp_pit_init();                                                             // 任务6：定时器中断（同时驱动按键扫描）
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     读取复位状态寄存器
// 返回参数     uint32
//-------------------------------------------------------------------------------------------------------------------
uint32 bsp_system_get_rcc_rstsc (void)
{
    return RCC->RSTSCKR;
}
