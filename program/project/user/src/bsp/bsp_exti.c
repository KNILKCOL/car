/*********************************************************************************************************************
* 文件名称          bsp_exti.c
* 功能简介          按键外部中断 BSP 驱动（任务9）
********************************************************************************************************************/
#include "bsp_exti.h"

static volatile uint8  bsp_exti_flag  = 0;                                      // 外部中断触发标志
static volatile uint32 bsp_exti_count = 0;                                      // 外部中断累计触发次数
static uint8           bsp_exti_inited = 0;

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     按键外部中断初始化
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void bsp_exti_init (void)
{
#if BSP_KEY_EXTI_ENABLE
    // 引脚已在 bsp_key_init 中配置为输入，这里只登记中断线与触发方式
    exti_init(BSP_KEY_EXTI_PIN_0, BSP_KEY_EXTI_TRIGGER);                        // D8  -> EXTI_Line8  (EXTI9_5_IRQHandler)
    exti_init(BSP_KEY_EXTI_PIN_1, BSP_KEY_EXTI_TRIGGER);                        // B12 -> EXTI_Line12 (EXTI15_10_IRQHandler)

    bsp_exti_flag   = 0;
    bsp_exti_count  = 0;
    bsp_exti_inited = 1;
#endif
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     按键外部中断服务函数（由 isr.c 调用）
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void bsp_exti_key_isr (void)
{
    bsp_exti_flag = 1;
    bsp_exti_count++;
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     查询并清除"外部中断触发"标志
// 返回参数     uint8        1-发生过外部中断 0-没有
//-------------------------------------------------------------------------------------------------------------------
uint8 bsp_exti_get_flag (void)
{
    uint8 flag = bsp_exti_flag;
    bsp_exti_flag = 0;
    return flag;
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     清除外部中断触发标志
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void bsp_exti_clear_flag (void)
{
    bsp_exti_flag = 0;
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     获取按键外部中断累计触发次数
// 返回参数     uint32
//-------------------------------------------------------------------------------------------------------------------
uint32 bsp_exti_get_count (void)
{
    return bsp_exti_count;
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     外部中断使能 / 失能
// 参数说明     enable       1-使能 0-失能
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void bsp_exti_enable (uint8 enable)
{
    if(0 == bsp_exti_inited)
    {
        return;
    }

    if(enable)
    {
        exti_enable(BSP_KEY_EXTI_PIN_0);
        exti_enable(BSP_KEY_EXTI_PIN_1);
    }
    else
    {
        exti_disable(BSP_KEY_EXTI_PIN_0);
        exti_disable(BSP_KEY_EXTI_PIN_1);
    }
}
