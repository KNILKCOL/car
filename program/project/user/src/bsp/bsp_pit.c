/*********************************************************************************************************************
* 文件名称          bsp_pit.c
* 功能简介          定时器中断 PIT BSP 驱动（任务6 / 任务4 / 任务10）
********************************************************************************************************************/
#include "bsp_pit.h"
#include "bsp_led.h"
#include "bsp_key.h"
#include "bsp_pwm.h"

static volatile uint32 bsp_pit_tick_ms   = 0;                                   // 系统节拍计数
static volatile uint8  bsp_pit_led_on    = 1;                                   // 定时中断翻 LED 功能开关
static volatile uint8  bsp_pit_led_index = BSP_LED_DEFAULT_INDEX;               // 定时中断控制的 LED 编号
static volatile uint16 bsp_pit_led_period_ms = BSP_PIT_LED_MS;                  // 定时中断周期
static volatile uint32 bsp_pit_led_count = 0;                                   // 翻转次数

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     定时器中断初始化
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void bsp_pit_init (void)
{
    // TIM6：1ms 系统节拍
    pit_ms_init(BSP_PIT_SYSTEM_INDEX, BSP_PIT_SYSTEM_MS);

    // TIM7：LED 定时中断（任务6）
    pit_ms_init(BSP_PIT_LED_INDEX, bsp_pit_led_period_ms);

    bsp_pit_tick_ms = 0;
    bsp_pit_led_count = 0;
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     系统节拍中断服务函数（1ms 一次）
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void bsp_pit_system_isr (void)
{
    if(TIM_GetITStatus(BSP_PIT_SYSTEM_TIM, TIM_IT_Update) == RESET)
    {
        return;
    }
    TIM_ClearITPendingBit(BSP_PIT_SYSTEM_TIM, TIM_IT_Update);

    bsp_pit_tick_ms++;

    bsp_key_scan_1ms();                                                         // 按键扫描（消抖 / 长短按判定）
    bsp_buzzer_tick_1ms();                                                      // 蜂鸣器非阻塞发声计时
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     LED 定时中断服务函数（任务6：定时器中断直接控制 LED）
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void bsp_pit_led_isr (void)
{
    if(TIM_GetITStatus(BSP_PIT_LED_TIM, TIM_IT_Update) == RESET)
    {
        return;
    }
    TIM_ClearITPendingBit(BSP_PIT_LED_TIM, TIM_IT_Update);

    if(0 == bsp_pit_led_on)
    {
        return;
    }

    bsp_led_toggle(bsp_pit_led_index);                                          // 中断中翻转 LED
    bsp_pit_led_count++;
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     获取系统运行时间
// 返回参数     uint32       毫秒
//-------------------------------------------------------------------------------------------------------------------
uint32 bsp_pit_get_tick_ms (void)
{
    return bsp_pit_tick_ms;
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     判断距离上次记录是否已经到达指定间隔
// 参数说明     last_ms      记录变量地址
// 参数说明     period_ms    间隔(ms)
// 返回参数     uint8        1-时间到 0-还没到
//-------------------------------------------------------------------------------------------------------------------
uint8 bsp_pit_check_interval (uint32 *last_ms, uint32 period_ms)
{
    uint32 now;

    if(0 == last_ms)
    {
        return 0;
    }

    now = bsp_pit_tick_ms;
    if((now - *last_ms) >= period_ms)
    {
        *last_ms = now;
        return 1;
    }
    return 0;
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     使能/关闭"定时器中断控制 LED"功能
// 参数说明     enable       1-使能 0-关闭
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void bsp_pit_led_enable (uint8 enable)
{
    bsp_pit_led_on = (0 != enable) ? (1) : (0);
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     设置"定时器中断控制 LED"使用的 LED 编号
// 参数说明     index        LED 编号 1 ~ BSP_LED_NUM
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void bsp_pit_led_set_index (uint8 index)
{
    if((index < 1) || (index > BSP_LED_NUM))
    {
        return;
    }
    bsp_pit_led_index = index;
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     获取"定时器中断控制 LED"的翻转次数
// 返回参数     uint32
//-------------------------------------------------------------------------------------------------------------------
uint32 bsp_pit_led_get_count (void)
{
    return bsp_pit_led_count;
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     修改 LED 定时中断周期（ms）
// 参数说明     period_ms    新的周期
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void bsp_pit_led_set_period (uint32 period_ms)
{
    if(0 == period_ms)
    {
        return;
    }
    if(period_ms > 5000)
    {
        period_ms = 5000;
    }

    bsp_pit_led_period_ms = (uint16)period_ms;
    pit_init(BSP_PIT_LED_INDEX, (uint32)bsp_pit_led_period_ms * (system_clock / 1000));
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     获取 LED 定时中断当前周期（ms）
// 返回参数     uint32
//-------------------------------------------------------------------------------------------------------------------
uint32 bsp_pit_led_get_period (void)
{
    return bsp_pit_led_period_ms;
}
