/*********************************************************************************************************************
* 文件名称          bsp_exti.h
* 功能简介          按键外部中断 BSP 驱动（任务9）
* 说明              编码器的 A0(D8)/A1(B12) 两个输出已经能覆盖全部按键组合，
*                   因此只注册 2 路线外部中断做"有按键动作"的事件通知，
*                   主循环/定时中断再用 GPIO 扫描做消抖确认。
********************************************************************************************************************/
#ifndef _bsp_exti_h_
#define _bsp_exti_h_

#include "bsp_board.h"

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     按键外部中断初始化
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    bsp_exti_init           (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     按键外部中断服务函数（由 isr.c 的 EXTI9_5 / EXTI15_10 调用）
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    bsp_exti_key_isr        (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     查询并清除"外部中断触发"标志
// 返回参数     uint8        1-自上次调用后发生过外部中断 0-没有
//-------------------------------------------------------------------------------------------------------------------
uint8   bsp_exti_get_flag       (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     清除外部中断触发标志
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    bsp_exti_clear_flag     (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     获取按键外部中断累计触发次数（用于任务9 界面显示）
// 返回参数     uint32
//-------------------------------------------------------------------------------------------------------------------
uint32  bsp_exti_get_count      (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     外部中断使能 / 失能
// 参数说明     enable       1-使能 0-失能
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    bsp_exti_enable         (uint8 enable);

#endif
