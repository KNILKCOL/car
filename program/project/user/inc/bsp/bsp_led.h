/*********************************************************************************************************************
* 文件名称          bsp_led.h
* 功能简介          LED 指示灯 BSP 驱动（任务3 / 任务6）
* 说明              所有硬件相关的引脚 / 电平 均由 bsp_board.h 中的宏定义决定。
********************************************************************************************************************/
#ifndef _bsp_led_h_
#define _bsp_led_h_

#include "bsp_board.h"

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     LED 初始化（把 BSP_LED1~5 全部配置为推挽输出并熄灭）
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    bsp_led_init        (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     点亮指定编号的 LED
// 参数说明     index        LED 编号 1 ~ BSP_LED_NUM
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    bsp_led_on          (uint8 index);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     熄灭指定编号的 LED
// 参数说明     index        LED 编号 1 ~ BSP_LED_NUM
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    bsp_led_off         (uint8 index);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     翻转指定编号的 LED
// 参数说明     index        LED 编号 1 ~ BSP_LED_NUM
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    bsp_led_toggle      (uint8 index);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     设置指定编号 LED 的状态
// 参数说明     index        LED 编号 1 ~ BSP_LED_NUM
// 参数说明     state        0-熄灭 1-点亮
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    bsp_led_set         (uint8 index, uint8 state);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     读取指定编号 LED 当前状态
// 参数说明     index        LED 编号 1 ~ BSP_LED_NUM
// 返回参数     uint8        0-熄灭 1-点亮
//-------------------------------------------------------------------------------------------------------------------
uint8   bsp_led_get         (uint8 index);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     所有 LED 全开
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    bsp_led_all_on      (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     所有 LED 全关
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    bsp_led_all_off     (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     获取指定编号 LED 对应的引脚
// 参数说明     index        LED 编号 1 ~ BSP_LED_NUM
// 返回参数     gpio_pin_enum 引脚枚举，编号非法时返回 PIN_NULL
//-------------------------------------------------------------------------------------------------------------------
gpio_pin_enum bsp_led_pin   (uint8 index);

#endif
