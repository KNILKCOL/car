/*********************************************************************************************************************
* 文件名称          bsp_pit.h
* 功能简介          定时器中断 PIT BSP 驱动（任务6 定时中断控制 LED / 任务4 按键扫描 / 任务10 菜单计时）
* 说明              TIM6 -> 1ms 系统节拍（按键扫描、UI 刷新计时）
*                   TIM7 -> LED 定时中断（中断内直接翻转 LED，对应任务6）
********************************************************************************************************************/
#ifndef _bsp_pit_h_
#define _bsp_pit_h_

#include "bsp_board.h"

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     定时器中断初始化（TIM6 系统节拍 + TIM7 LED 定时中断）
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    bsp_pit_init            (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     系统节拍中断服务函数（由 isr.c 的 TIM6_IRQHandler 调用）
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    bsp_pit_system_isr      (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     LED 定时中断服务函数（由 isr.c 的 TIM7_IRQHandler 调用）
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    bsp_pit_led_isr         (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     获取系统运行时间（1ms 步进）
// 返回参数     uint32       毫秒
//-------------------------------------------------------------------------------------------------------------------
uint32  bsp_pit_get_tick_ms     (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     判断距离上次记录是否已经到达指定间隔，到达则更新记录并返回 1
// 参数说明     last_ms      记录变量地址
// 参数说明     period_ms    间隔(ms)
// 返回参数     uint8        1-时间到 0-还没到
//-------------------------------------------------------------------------------------------------------------------
uint8   bsp_pit_check_interval  (uint32 *last_ms, uint32 period_ms);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     使能/关闭"定时器中断控制 LED"功能（任务6）
// 参数说明     enable       1-使能 0-关闭
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    bsp_pit_led_enable      (uint8 enable);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     设置"定时器中断控制 LED"使用的 LED 编号
// 参数说明     index        LED 编号 1 ~ BSP_LED_NUM
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    bsp_pit_led_set_index   (uint8 index);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     获取"定时器中断控制 LED"的翻转次数（用于界面显示）
// 返回参数     uint32
//-------------------------------------------------------------------------------------------------------------------
uint32  bsp_pit_led_get_count   (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     修改 LED 定时中断周期（任务10 可调参数，单位 ms）
// 参数说明     period_ms    新的周期
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    bsp_pit_led_set_period  (uint32 period_ms);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     获取 LED 定时中断当前周期（ms）
// 返回参数     uint32
//-------------------------------------------------------------------------------------------------------------------
uint32  bsp_pit_led_get_period  (void);

#endif
