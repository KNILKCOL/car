/*********************************************************************************************************************
* 文件名称          bsp_lcd.h
* 功能简介          SPI 屏幕 BSP 驱动（任务7 / 任务9 / 任务10）
* 硬件连接          1.8 寸 TFT(ST7735) 128x160
*                   SCL=PB13(SPI2_SCK) SDA=PB15(SPI2_MOSI) RES=PB7 DC=PD7 CS=PD4 BL=PD0
*                   引脚与开源库 zf_device_tft180 默认配置一致，直接复用该驱动，
*                   本文件只做"按字符行列显示"的封装，方便 app 层写 UI。
********************************************************************************************************************/
#ifndef _bsp_lcd_h_
#define _bsp_lcd_h_

#include "bsp_board.h"

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     屏幕初始化（含 SPI2 初始化）
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    bsp_lcd_init        (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     整屏填充
// 参数说明     color        RGB565 颜色
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    bsp_lcd_clear       (uint16 color);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     在指定行列显示字符串（黑色字 / 白色底）
// 参数说明     col          列 0 ~ BSP_LCD_COLS-1
// 参数说明     row          行 0 ~ BSP_LCD_ROWS-1
// 参数说明     str          字符串（仅支持 ASCII）
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    bsp_lcd_puts        (uint16 col, uint16 row, const char *str);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     在指定行列显示字符串（自定义前景色 / 背景色）
// 参数说明     col, row     行列
// 参数说明     str          字符串
// 参数说明     pen          前景色
// 参数说明     bg           背景色
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    bsp_lcd_puts_color  (uint16 col, uint16 row, const char *str, uint16 pen, uint16 bg);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     在指定行列显示整数
// 参数说明     col, row     行列
// 参数说明     dat          数值
// 参数说明     num          显示位数
// 参数说明     pen, bg      前景色 / 背景色
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    bsp_lcd_put_int     (uint16 col, uint16 row, int32 dat, uint8 num, uint16 pen, uint16 bg);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     清空一整行（填充为背景色）
// 参数说明     row          行号
// 参数说明     bg           背景色
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    bsp_lcd_clear_row   (uint16 row, uint16 bg);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     填充一个矩形区域
// 参数说明     x, y         左上角坐标(像素)
// 参数说明     w, h         宽 / 高(像素)
// 参数说明     color        RGB565 颜色
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    bsp_lcd_fill_rect   (uint16 x, uint16 y, uint16 w, uint16 h, uint16 color);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     在屏幕上显示一幅灰度图像（任务7 屏幕驱动验证用，占空图案/渐变）
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    bsp_lcd_draw_test_pattern (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     屏幕背光开关（任务10 三级菜单 BRIGHT 参数实际生效的地方）
// 参数说明     on           1-打开背光 0-关闭背光
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    bsp_lcd_set_backlight (uint8 on);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     查询背光状态
// 返回参数     uint8        1-开 0-关
//-------------------------------------------------------------------------------------------------------------------
uint8   bsp_lcd_get_backlight (void);

#endif
