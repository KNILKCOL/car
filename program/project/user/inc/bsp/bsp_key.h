/*********************************************************************************************************************
* 文件名称          bsp_key.h
* 功能简介          按键 BSP 驱动（任务4 读取按键状态 / 任务9 UI 交互 / 任务10 菜单操作）
* 硬件连接          五向开关 + KEY1/KEY2 -> SN74HC148 编码器 -> KEY_IN3_B14 / KEY_IN2_B12 / KEY_IN1_D8
*                   即 MCU 只占用 3 个 GPIO 就能读出 7 个按键，编码对应关系见 bsp_board.h
********************************************************************************************************************/
#ifndef _bsp_key_h_
#define _bsp_key_h_

#include "bsp_board.h"

// 按键枚举（与 bsp_board.h 中的编码宏一一对应）
typedef enum
{
    BSP_KEY_NONE = 0,                                                           // 无按键
    BSP_KEY_KEY1,                                                               // 编码 0
    BSP_KEY_KEY2,                                                               // 编码 1
    BSP_KEY_MID,                                                                // 编码 2  中键(确定)
    BSP_KEY_RIGHT,                                                              // 编码 3  右键
    BSP_KEY_UP,                                                                 // 编码 4  上键
    BSP_KEY_DOWN,                                                               // 编码 5  下键
    BSP_KEY_LEFT,                                                               // 编码 6  左键

    BSP_KEY_NUMBER,                                                             // 按键总数
}bsp_key_enum;

// 按键事件
typedef enum
{
    BSP_KEY_STATE_RELEASE = 0,                                                  // 无事件
    BSP_KEY_STATE_SHORT,                                                        // 短按
    BSP_KEY_STATE_LONG,                                                         // 长按(按住不放会按 BSP_KEY_LONG_PRESS_MS 周期重复上报)
}bsp_key_state_enum;

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     按键初始化（3 路 GPIO 输入 + 上拉 + 外部中断）
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void                bsp_key_init            (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     直接读取 3 路 GPIO 组合出的原始编码（未消抖）
// 返回参数     uint8       0 ~ 7，7 表示无按键
//-------------------------------------------------------------------------------------------------------------------
uint8               bsp_key_read_code       (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     把编码值转换为按键枚举
// 参数说明     code         编码值 0 ~ 7
// 返回参数     bsp_key_enum
//-------------------------------------------------------------------------------------------------------------------
bsp_key_enum        bsp_key_code_to_key     (uint8 code);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     按键扫描（必须由 1ms 定时器中断周期调用，内部完成消抖与长短按判定）
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void                bsp_key_scan_1ms        (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     取出一条按键事件（先进先出，取走后自动清除）
// 参数说明     key          输出参数，返回事件对应的按键
// 返回参数     bsp_key_state_enum   BSP_KEY_STATE_RELEASE 表示当前没有事件
//-------------------------------------------------------------------------------------------------------------------
bsp_key_state_enum  bsp_key_get_event       (bsp_key_enum *key);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     查询某个按键当前是否处于按下状态（已消抖）
// 参数说明     key          按键
// 返回参数     uint8        1-按下 0-松开
//-------------------------------------------------------------------------------------------------------------------
uint8               bsp_key_is_pressed      (bsp_key_enum key);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     查询当前按下的按键（已消抖）
// 返回参数     bsp_key_enum BSP_KEY_NONE 表示没有按键按下
//-------------------------------------------------------------------------------------------------------------------
bsp_key_enum        bsp_key_get_pressed     (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     查询某个按键已经按住的时长
// 参数说明     key          按键
// 返回参数     uint16       毫秒
//-------------------------------------------------------------------------------------------------------------------
uint16              bsp_key_get_press_ms    (bsp_key_enum key);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     获取已经处理过的按键事件总次数（调试用）
// 返回参数     uint32
//-------------------------------------------------------------------------------------------------------------------
uint32              bsp_key_get_event_count (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     获取按键名称字符串（供屏幕显示）
// 参数说明     key          按键
// 返回参数     const char*  名称
//-------------------------------------------------------------------------------------------------------------------
const char*         bsp_key_name            (bsp_key_enum key);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     动态修改按键消抖时间（任务10 三级菜单可调参数）
// 参数说明     ms           消抖时间(ms)，0 表示使用宏定义默认值
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void                bsp_key_set_debounce_ms (uint16 ms);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     获取当前按键消抖时间
// 返回参数     uint16       ms
//-------------------------------------------------------------------------------------------------------------------
uint16              bsp_key_get_debounce_ms (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     动态修改长按判定时间（任务10 三级菜单可调参数）
// 参数说明     ms           长按判定时间(ms)，0 表示使用宏定义默认值
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void                bsp_key_set_long_press_ms (uint16 ms);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     获取当前长按判定时间
// 返回参数     uint16       ms
//-------------------------------------------------------------------------------------------------------------------
uint16              bsp_key_get_long_press_ms (void);

#endif
