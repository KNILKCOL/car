/*********************************************************************************************************************
* 文件名称          bsp_pwm.h
* 功能简介          PWM BSP 驱动 —— 无源蜂鸣器 + PWM 波形输出（任务5）
* 硬件连接          FMQ_IO_A8 -> 20Ω -> AO3400A 栅极 -> 无源蜂鸣器(2.731kHz) -> GND
*                   DUOJI_PWM_C6 (舵机接口) 作为第二路 PWM 波形输出演示
********************************************************************************************************************/
#ifndef _bsp_pwm_h_
#define _bsp_pwm_h_

#include "bsp_board.h"

/*********************************************************************************************************************
*                                          无源蜂鸣器（PWM 驱动）
********************************************************************************************************************/
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     蜂鸣器初始化（TIM1_CH1 / PA8，频率为原理图标注的谐振频率）
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    bsp_buzzer_init         (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     蜂鸣器开始发声（占空比 50%）
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    bsp_buzzer_on           (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     蜂鸣器停止发声
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    bsp_buzzer_off          (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     设置蜂鸣器发声频率（无源蜂鸣器必须用方波驱动，频率越接近谐振频率越响）
// 参数说明     freq_hz      频率(Hz)
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    bsp_buzzer_set_freq     (uint32 freq_hz);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     设置蜂鸣器占空比
// 参数说明     duty         占空比 0 ~ PWM_DUTY_MAX
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    bsp_buzzer_set_duty     (uint32 duty);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     蜂鸣器响一声（阻塞方式）
// 参数说明     ms           持续时间(ms)
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    bsp_buzzer_beep         (uint32 ms);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     蜂鸣器响一声（非阻塞方式，需要在系统节拍中调用 bsp_buzzer_tick_1ms）
// 参数说明     ms           持续时间(ms)
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    bsp_buzzer_beep_start   (uint32 ms);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     蜂鸣器非阻塞计时（由 1ms 系统节拍调用）
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    bsp_buzzer_tick_1ms     (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     查询蜂鸣器是否正在发声
// 返回参数     uint8        1-正在发声 0-静音
//-------------------------------------------------------------------------------------------------------------------
uint8   bsp_buzzer_is_on        (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     查询蜂鸣器当前频率
// 返回参数     uint32       Hz
//-------------------------------------------------------------------------------------------------------------------
uint32  bsp_buzzer_get_freq     (void);

/*********************************************************************************************************************
*                                          第二路 PWM 波形输出（任务5）
********************************************************************************************************************/
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     第二路 PWM 演示输出初始化
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    bsp_pwm_demo_init       (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     设置第二路 PWM 的频率与占空比
// 参数说明     freq_hz      频率(Hz)
// 参数说明     duty         占空比 0 ~ PWM_DUTY_MAX
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    bsp_pwm_demo_set        (uint32 freq_hz, uint32 duty);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     设置第二路 PWM 的占空比（频率不变）
// 参数说明     duty         占空比 0 ~ PWM_DUTY_MAX
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    bsp_pwm_demo_set_duty   (uint32 duty);

#endif
