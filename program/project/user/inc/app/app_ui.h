/*********************************************************************************************************************
* 文件名称          app_ui.h
* 功能简介          屏幕 UI 绘制组件（app 层，任务9 / 任务10）
* 说明              屏幕 128x160，8x16 字体 => 16 列 10 行。
*                   行 0 = 标题栏，行 1~8 = 内容区，行 9 = 状态栏。
*                   屏幕驱动只支持 ASCII 字符，因此界面文字全部使用英文缩写。
********************************************************************************************************************/
#ifndef _app_ui_h_
#define _app_ui_h_

#include "bsp_board.h"
#include "bsp_key.h"

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     UI 初始化（清屏并画好背景）
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    app_ui_init         (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     绘制标题栏
// 参数说明     title        标题字符串
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    app_ui_title        (const char *title);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     清空内容区（行 1 ~ 行 8）
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    app_ui_clear_body   (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     在指定行显示字符串（自动限制在内容区内）
// 参数说明     row          行号(0 ~ 9)
// 参数说明     str          字符串
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    app_ui_text         (uint16 row, const char *str);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     在指定行显示带颜色的字符串
// 参数说明     row          行号
// 参数说明     str          字符串
// 参数说明     pen, bg      前景色 / 背景色
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    app_ui_text_color   (uint16 row, const char *str, uint16 pen, uint16 bg);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     显示一行菜单项：光标 + 名称 + 值
// 参数说明     row          行号
// 参数说明     label        名称
// 参数说明     value        值字符串，可为 0
// 参数说明     selected     1-当前选中(高亮) 0-普通
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    app_ui_menu_item    (uint16 row, const char *label, const char *value, uint8 selected);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     显示一行"名称 + 整数"信息
// 参数说明     row          行号
// 参数说明     label        名称
// 参数说明     value        数值
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    app_ui_value_int    (uint16 row, const char *label, int32 value);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     绘制状态栏（显示当前按键 / 提示）
// 参数说明     str          状态字符串
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    app_ui_status       (const char *str);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     居中显示一条提示信息
// 参数说明     line1        第一行
// 参数说明     line2        第二行，可为 0
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    app_ui_message      (const char *line1, const char *line2);

#endif
