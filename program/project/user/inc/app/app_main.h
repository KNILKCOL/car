/*********************************************************************************************************************
* 文件名称          app_main.h
* 功能简介          应用主流程（app 层）：页面管理 + 主循环（任务11 的"不重新烧录"核心）
* 说明              main() 里只做两件事：
*                       1. app_main_init()  初始化 BSP 和应用
*                       2. while(1) app_main_loop()
*                   所有任务页面都挂在 app_page_table 上，通过五向开关切换，
*                   因此全部考核任务可以在同一次烧录中完成。
********************************************************************************************************************/
#ifndef _app_main_h_
#define _app_main_h_

#include "bsp_board.h"
#include "bsp_key.h"

// 页面编号（顺序即主菜单的显示顺序）
typedef enum
{
    APP_PAGE_MAIN = 0,                                                          // 任务总菜单（任务11）
    APP_PAGE_LED,                                                               // 任务3
    APP_PAGE_KEY,                                                               // 任务4
    APP_PAGE_PWM,                                                               // 任务5
    APP_PAGE_TIMER,                                                             // 任务6
    APP_PAGE_LCD,                                                               // 任务7
    APP_PAGE_FLASH,                                                             // 任务8
    APP_PAGE_EXTI,                                                              // 任务9
    APP_PAGE_MENU,                                                              // 任务10

    APP_PAGE_NUMBER
}app_page_enum;

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     应用初始化（BSP 初始化 -> 参数初始化 -> 进入主菜单）
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    app_main_init       (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     应用主循环（在 main 的 while(1) 中反复调用）
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    app_main_loop       (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     切换到指定页面
// 参数说明     page         页面编号
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    app_main_goto_page  (app_page_enum page);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     返回任务总菜单
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void    app_main_goto_main  (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     获取当前页面编号
// 返回参数     app_page_enum
//-------------------------------------------------------------------------------------------------------------------
app_page_enum app_main_get_page (void);

#endif
