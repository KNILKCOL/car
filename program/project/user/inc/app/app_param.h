/*********************************************************************************************************************
* 文件名称          app_param.h
* 功能简介          参数管理（任务8 Flash 存储 / 任务10 三级菜单记录的参数）
* 说明              参数分 3 组，每组 3 个，共 9 个参数（正好构成"三级菜单"的数据基础）。
*                   参数保存在 Flash 扇区 63，掉电不丢失。
********************************************************************************************************************/
#ifndef _app_param_h_
#define _app_param_h_

#include "bsp_board.h"

#define APP_PARAM_GROUP_NUM         (3)                                         // 参数组数（三级菜单的第一级）
#define APP_PARAM_PER_GROUP         (3)                                         // 每组参数个数（三级菜单的第二级）
#define APP_PARAM_TOTAL             (APP_PARAM_GROUP_NUM * APP_PARAM_PER_GROUP)

// 单个参数项
typedef struct
{
    const char *name;                                                           // 参数名称（显示用，ASCII）
    int32       min;                                                            // 最小值
    int32       max;                                                            // 最大值
    int32       step;                                                           // 调节步长
    int32       value;                                                          // 当前值
    int32       def_value;                                                      // 默认值
}app_param_item_struct;

// 参数组
typedef struct
{
    const char *name;                                                           // 组名称
    app_param_item_struct item[APP_PARAM_PER_GROUP];
}app_param_group_struct;

// 掉电保存的数据结构（会被原样写入 Flash）
typedef struct
{
    uint32 boot_count;                                                          // 开机次数（证明数据掉电保存成功）
    int32  value[APP_PARAM_TOTAL];                                              // 9 个参数值
}app_param_store_struct;

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     参数初始化（先把参数表恢复成默认值，再从 Flash 读取保存过的值）
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void                    app_param_init          (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     把当前参数保存到 Flash
// 返回参数     uint8        0-成功 其它-失败
//-------------------------------------------------------------------------------------------------------------------
uint8                   app_param_save          (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     从 Flash 读取参数并生效（任务8 "能够读取保存的数据"）
// 返回参数     uint8        0-成功 其它-失败（无数据或校验失败则保持当前值不变）
//-------------------------------------------------------------------------------------------------------------------
uint8                   app_param_load          (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     把参数恢复成默认值（不写 Flash，需要再调用 app_param_save）
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void                    app_param_reset_default (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     获取指定参数组
// 参数说明     group        组下标 0 ~ APP_PARAM_GROUP_NUM-1
// 返回参数     app_param_group_struct*
//-------------------------------------------------------------------------------------------------------------------
app_param_group_struct *app_param_get_group     (uint8 group);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     获取某个参数项
// 参数说明     group        组下标
// 参数说明     index        组内下标
// 返回参数     app_param_item_struct*
//-------------------------------------------------------------------------------------------------------------------
app_param_item_struct  *app_param_get_item      (uint8 group, uint8 index);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     修改参数值（自动按 min/max/step 规范化）
// 参数说明     group        组下标
// 参数说明     index        组内下标
// 参数说明     value        新值
// 返回参数     int32        规范化之后的实际值
//-------------------------------------------------------------------------------------------------------------------
int32                   app_param_set_value     (uint8 group, uint8 index, int32 value);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     在参数值基础上增加/减少一个步长
// 参数说明     group        组下标
// 参数说明     index        组内下标
// 参数说明     dir          1-增加 -1-减少
// 返回参数     int32        调整之后的实际值
//-------------------------------------------------------------------------------------------------------------------
int32                   app_param_step_value    (uint8 group, uint8 index, int8 dir);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     获取开机次数（保存在 Flash 中，掉电不丢失）
// 返回参数     uint32
//-------------------------------------------------------------------------------------------------------------------
uint32                  app_param_get_boot_count(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     获取上一次上电时 Flash 中已经存在的开机次数（用于对比，证明数据被保存了）
// 返回参数     uint32
//-------------------------------------------------------------------------------------------------------------------
uint32                  app_param_get_prev_boot (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     获取最后一次 Flash 保存的结果
// 返回参数     uint8        0-成功 其它-失败
//-------------------------------------------------------------------------------------------------------------------
uint8                   app_param_get_last_result (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     把参数值同步到 BSP 层（例如 LED 闪烁周期、UI 刷新周期、消抖时间等）
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void                    app_param_apply_to_bsp  (void);

#endif
